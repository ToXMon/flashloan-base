//! Gating Layer — Signal pipeline gate for regime-aware directional trading
//!
//! Sits between signal sources and gRPC output. Only passes DirectionalSignal
//! if market regime matches the signal direction. Emits RegimeUpdate on regime
//! transitions.
//!
//! Gating rules (Trading Maestro):
//! - TrendingUp   → pass LONG signals only
//! - TrendingDown → discard all (no short capability in MVP)
//! - Ranging      → discard all directional
//! - Breakout     → discard unless signal confidence > 0.85

use serde::{Deserialize, Serialize};

use crate::regime_detector::{RegimeType, RegimeUpdate, TrendDirection};

// ── Re-export for access by callers ──────────────────────────────────

pub use crate::regime_detector::RegimeUpdate as GatedRegimeUpdate;

// ── Trade Direction ──────────────────────────────────────────────────

/// Direction of a directional trade signal.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TradeDirection {
    /// Long position (buy)
    Long,
    /// Short position (sell) — reserved for Phase 2
    Short,
}

impl TradeDirection {
    pub fn label(&self) -> &'static str {
        match self {
            TradeDirection::Long => "Long",
            TradeDirection::Short => "Short",
        }
    }
}

// ── Directional Signal ───────────────────────────────────────────────

/// A directional trading signal generated by the trend scanner.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DirectionalSignal {
    /// Trading pair (e.g. "WETH/USDC")
    pub pair: String,
    /// Trade direction (Long only for MVP)
    pub direction: TradeDirection,
    /// Proposed entry price
    pub entry_price: f64,
    /// Stop-loss price (entry - 1.5x ATR)
    pub stop_loss: f64,
    /// Take-profit price (entry + 3x ATR)
    pub take_profit: f64,
    /// Combined confidence score 0..1
    pub confidence: f64,
    /// Human-readable regime label that confirmed this signal
    pub regime_confirmed: String,
    /// Block number at which this signal expires
    pub expires_at: i64,
    /// Unix timestamp (milliseconds) when signal was generated
    pub detected_at_ms: i64,
}

// ── Gate Decision ────────────────────────────────────────────────────

/// Result of gating a single directional signal.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum GateDecision {
    /// Signal passed the gate and is actionable
    Allow,
    /// Signal was blocked with a reason
    Block {
        /// Human-readable reason for blocking
        reason: String,
    },
}

// ── Gated Signal ─────────────────────────────────────────────────────

/// A directional signal with its gating decision.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GatedSignal {
    /// The directional signal
    pub signal: DirectionalSignal,
    /// The gate's decision
    pub decision: GateDecision,
}

// ── Gated Result ─────────────────────────────────────────────────────

/// Full result of a gating evaluation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GatedResult {
    /// Signals that passed the gate (actionable)
    pub allowed_signals: Vec<DirectionalSignal>,
    /// Signals that were blocked, each with a reason
    pub blocked_signals: Vec<(DirectionalSignal, String)>,
    /// Regime update if the regime has changed since the last evaluation
    pub regime_update: Option<RegimeUpdate>,
}

impl GatedResult {
    /// Create an empty gated result
    pub fn empty() -> Self {
        Self {
            allowed_signals: Vec::new(),
            blocked_signals: Vec::new(),
            regime_update: None,
        }
    }

    /// Returns true if any signal passed the gate
    pub fn has_actionable(&self) -> bool {
        !self.allowed_signals.is_empty()
    }

    /// Total signals evaluated
    pub fn total_signals(&self) -> usize {
        self.allowed_signals.len() + self.blocked_signals.len()
    }
}

// ── Gating Layer ─────────────────────────────────────────────────────

/// Signal pipeline gate that only passes regime-matching directional signals.
///
/// The gating layer sits between signal sources (trend scanner, etc.) and
/// the gRPC output. It enforces Trading Maestro rules:
/// - In trending_up regimes, only LONG signals pass
/// - In ranging regimes, all directional signals are blocked
/// - In breakout regimes, only high-confidence signals pass
/// - Regime transitions emit a RegimeUpdate event
#[derive(Debug, Clone)]
pub struct GatingLayer {
    /// Previous regime for transition detection
    previous_regime: Option<RegimeType>,
}

impl GatingLayer {
    /// Create a new gating layer with no prior regime state
    pub fn new() -> Self {
        Self {
            previous_regime: None,
        }
    }

    /// Create a gating layer with a known initial regime
    pub fn with_initial_regime(regime: RegimeType) -> Self {
        Self {
            previous_regime: Some(regime),
        }
    }

    /// Evaluate directional signals against the current market regime.
    ///
    /// This is the main entry point. It applies gating rules deterministically
    /// and emits a RegimeUpdate if the regime has changed since the last call.
    pub fn evaluate(
        &mut self,
        current_regime: &RegimeType,
        current_direction: &TrendDirection,
        signals: Vec<DirectionalSignal>,
        regime_update: Option<RegimeUpdate>,
    ) -> GatedResult {
        // 1. Detect regime change and emit update
        let mut result = GatedResult::empty();

        let regime_changed = match self.previous_regime {
            Some(prev) => prev != *current_regime,
            None => true, // first evaluation always emits the initial regime
        };

        if regime_changed {
            result.regime_update = regime_update;
        }

        self.previous_regime = Some(*current_regime);

        // 2. Gate each signal according to regime rules
        for signal in signals {
            let decision = Self::apply_regime_gate(current_regime, current_direction, &signal);
            match decision {
                GateDecision::Allow => {
                    result.allowed_signals.push(signal);
                }
                GateDecision::Block { reason } => {
                    result.blocked_signals.push((signal, reason));
                }
            }
        }

        result
    }

    /// Apply regime-based gating to a single directional signal.
    ///
    /// Rules (from Trading Maestro Courses 1-4):
    /// - TrendingUp + TrendDirection::Bullish → Allow LONG signals
    /// - TrendingDown → Block all (no short capability in MVP)
    /// - Ranging → Block all directional
    /// - Breakout → Block unless signal confidence > 0.85
    /// - Reversal → Block (conservative; wait for trend confirmation)
    fn apply_regime_gate(
        current_regime: &RegimeType,
        current_direction: &TrendDirection,
        signal: &DirectionalSignal,
    ) -> GateDecision {
        match current_regime {
            RegimeType::Trending => {
                match signal.direction {
                    TradeDirection::Long => {
                        // Trending regime: only allow LONG when trend is Bullish
                        if *current_direction != TrendDirection::Bullish {
                            return GateDecision::Block {
                                reason: format!("Trending but direction is {:?} — only Bullish trending allows LONG", current_direction),
                            };
                        }
                        GateDecision::Allow
                    }
                    TradeDirection::Short => {
                        GateDecision::Block {
                            reason: "Short positions not supported in MVP; trending regime only passes LONG signals".into(),
                        }
                    }
                }
            }
            RegimeType::Ranging => {
                GateDecision::Block {
                    reason: format!(
                        "Regime is Ranging — no directional signals pass; {} signal blocked",
                        signal.direction.label()
                    ),
                }
            }
            RegimeType::Breakout => {
                if signal.confidence > 0.85 {
                    GateDecision::Allow
                } else {
                    GateDecision::Block {
                        reason: format!(
                            "Breakout regime requires confidence > 0.85; got {:.2}",
                            signal.confidence
                        ),
                    }
                }
            }
            RegimeType::Reversal => {
                GateDecision::Block {
                    reason: "Reversal regime — waiting for trend confirmation before accepting signals".into(),
                }
            }
        }
    }

    /// Get the previous regime (useful for external state inspection)
    pub fn previous_regime(&self) -> Option<RegimeType> {
        self.previous_regime
    }

    /// Reset the gating layer state (clear previous regime tracking)
    pub fn reset(&mut self) {
        self.previous_regime = None;
    }
}

impl Default for GatingLayer {
    fn default() -> Self {
        Self::new()
    }
}

// ── Stateless convenience function ───────────────────────────────────

/// Convenience function for one-shot gating without maintaining state.
///
/// Calls evaluate() on a fresh GatingLayer. Use this for stateless contexts
/// where regime transition tracking is not needed.
pub fn gate_signals(
    current_regime: &RegimeType,
    current_direction: &TrendDirection,
    signals: Vec<DirectionalSignal>,
    regime_update: Option<RegimeUpdate>,
) -> GatedResult {
    let mut layer = GatingLayer::new();
    layer.evaluate(current_regime, current_direction, signals, regime_update)
}

// ── Tests ────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;
    use crate::regime_detector::TrendDirection;

    fn make_signal(pair: &str, direction: TradeDirection, confidence: f64) -> DirectionalSignal {
        DirectionalSignal {
            pair: pair.to_string(),
            direction,
            entry_price: 1500.0,
            stop_loss: 1475.0,
            take_profit: 1550.0,
            confidence,
            regime_confirmed: "Trending".to_string(),
            expires_at: 100100,
            detected_at_ms: 1718000000000,
        }
    }

    fn make_regime_update(regime: RegimeType, confidence: f64) -> RegimeUpdate {
        RegimeUpdate {
            regime,
            trend_direction: TrendDirection::Bullish,
            volatility: 12.5,
            confidence,
            timestamp: 1718000000000,
        }
    }

    #[test]
    fn test_only_passes_trending_up_signals() {
        let mut layer = GatingLayer::new();
        let signals = vec![
            make_signal("WETH/USDC", TradeDirection::Long, 0.85),
            make_signal("WETH/USDC", TradeDirection::Short, 0.80),
        ];
        let regime_update = Some(make_regime_update(RegimeType::Trending, 0.85));
        let result = layer.evaluate(
            &RegimeType::Trending,
            &TrendDirection::Bullish,
            signals,
            regime_update,
        );

        assert_eq!(result.allowed_signals.len(), 1);
        assert_eq!(result.blocked_signals.len(), 1);
        assert_eq!(result.allowed_signals[0].direction, TradeDirection::Long);
        assert!(result.blocked_signals[0].1.contains("Short"));
        assert!(result.regime_update.is_some());
    }

    #[test]
    fn test_ranging_blocks_all_directional() {
        let signals = vec![
            make_signal("WETH/USDC", TradeDirection::Long, 0.75),
            make_signal("WETH/USDC", TradeDirection::Long, 0.90),
        ];
        let result = gate_signals(
            &RegimeType::Ranging,
            &TrendDirection::Neutral,
            signals,
            None,
        );

        assert_eq!(result.allowed_signals.len(), 0);
        assert_eq!(result.blocked_signals.len(), 2);
        for (_, reason) in &result.blocked_signals {
            assert!(reason.contains("Ranging"));
        }
    }

    #[test]
    fn test_breakout_high_bar_applied() {
        let signals = vec![
            make_signal("WETH/USDC", TradeDirection::Long, 0.80),
            make_signal("WETH/USDC", TradeDirection::Long, 0.90),
        ];
        let result = gate_signals(
            &RegimeType::Breakout,
            &TrendDirection::Bullish,
            signals,
            None,
        );

        assert_eq!(result.allowed_signals.len(), 1);
        assert_eq!(result.blocked_signals.len(), 1);
        assert_eq!(result.allowed_signals[0].confidence, 0.90);
        assert_eq!(result.blocked_signals[0].0.confidence, 0.80);
    }

    #[test]
    fn test_trending_down_blocks_all() {
        let signals = vec![
            make_signal("WETH/USDC", TradeDirection::Long, 0.85),
            make_signal("WETH/USDC", TradeDirection::Short, 0.85),
        ];
        let result = gate_signals(
            &RegimeType::Trending,
            &TrendDirection::Bearish,
            signals,
            None,
        );

        // Bearish trending blocks all: Long blocked (wrong direction), Short blocked (MVP constraint)
        assert_eq!(result.allowed_signals.len(), 0);
        assert_eq!(result.blocked_signals.len(), 2);
    }

    #[test]
    fn test_reversal_blocks_all() {
        let signals = vec![
            make_signal("WETH/USDC", TradeDirection::Long, 0.90),
        ];
        let result = gate_signals(
            &RegimeType::Reversal,
            &TrendDirection::Neutral,
            signals,
            None,
        );

        assert_eq!(result.allowed_signals.len(), 0);
        assert_eq!(result.blocked_signals.len(), 1);
        assert!(result.blocked_signals[0].1.contains("Reversal"));
    }

    #[test]
    fn test_regime_change_emits_update() {
        let mut layer = GatingLayer::new();

        // First evaluation with Ranging
        let result1 = layer.evaluate(
            &RegimeType::Ranging,
            &TrendDirection::Neutral,
            vec![],
            Some(make_regime_update(RegimeType::Ranging, 0.5)),
        );
        assert!(result1.regime_update.is_some()); // first eval always emits

        // Same regime again → no update
        let result2 = layer.evaluate(
            &RegimeType::Ranging,
            &TrendDirection::Neutral,
            vec![],
            Some(make_regime_update(RegimeType::Ranging, 0.5)),
        );
        assert!(result2.regime_update.is_none());

        // Regime changes → emits update
        let result3 = layer.evaluate(
            &RegimeType::Trending,
            &TrendDirection::Bullish,
            vec![],
            Some(make_regime_update(RegimeType::Trending, 0.85)),
        );
        assert!(result3.regime_update.is_some());
        if let Some(ref update) = result3.regime_update {
            assert_eq!(update.regime, RegimeType::Trending);
        }
    }

    #[test]
    fn test_unchanged_regime_no_update() {
        let mut layer = GatingLayer::with_initial_regime(RegimeType::Trending);

        let result = layer.evaluate(
            &RegimeType::Trending,
            &TrendDirection::Bullish,
            vec![],
            Some(make_regime_update(RegimeType::Trending, 0.85)),
        );

        // Pre-seeded with Trending, so same regime → no update
        assert!(result.regime_update.is_none());
    }

    #[test]
    fn test_empty_signals_produces_empty_result() {
        let result = gate_signals(
            &RegimeType::Trending,
            &TrendDirection::Bullish,
            vec![],
            None,
        );
        assert_eq!(result.allowed_signals.len(), 0);
        assert_eq!(result.blocked_signals.len(), 0);
        assert!(result.regime_update.is_none());
        assert_eq!(result.total_signals(), 0);
        assert!(!result.has_actionable());
    }

    #[test]
    fn test_gated_result_helpers() {
        let empty = GatedResult::empty();
        assert_eq!(empty.total_signals(), 0);
        assert!(!empty.has_actionable());

        let non_empty = GatedResult {
            allowed_signals: vec![make_signal("WETH/USDC", TradeDirection::Long, 0.80)],
            blocked_signals: vec![],
            regime_update: None,
        };
        assert!(non_empty.has_actionable());
        assert_eq!(non_empty.total_signals(), 1);
    }

    #[test]
    fn test_gating_layer_reset() {
        let mut layer = GatingLayer::with_initial_regime(RegimeType::Trending);

        // After reset, previous regime is None → first eval emits update
        layer.reset();
        assert!(layer.previous_regime().is_none());

        let result = layer.evaluate(
            &RegimeType::Trending,
            &TrendDirection::Bullish,
            vec![],
            Some(make_regime_update(RegimeType::Trending, 0.85)),
        );
        assert!(result.regime_update.is_some());
    }
}
